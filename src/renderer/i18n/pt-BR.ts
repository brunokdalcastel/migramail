export type TextKey = keyof typeof ptBR
export type Dictionary = Record<TextKey, string>

/** Texto da chave com `{nome}` trocado pelos valores (variável ausente fica como está). */
export function t(key: TextKey, vars?: Record<string, string | number>): string {
  const text: string = ptBR[key]
  return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => String(vars[name] ?? m)) : text
}

const numberFormat = new Intl.NumberFormat('pt-BR')
/** `2340` → `2.340`. */
export const fmtNumber = (n: number): string => numberFormat.format(n)
